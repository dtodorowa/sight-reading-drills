// Importer: turn the hand-authored practice MusicXML in the learning-piano
// notebook into a NoteDash data module of playable exercises.
//
// The learning-piano repo stays the source of truth (that is where the "teach
// me" skill authors lessons and generates practice files). This script is the
// one-way bridge into the app: run it whenever new practice files land.
//
//   node tools/import-practice.mjs [sourceDir]
//
// sourceDir defaults to ../learning-piano/practice (the repos sit side by side).
// It reads every *.musicxml, pulls the note sequence (pitch only, rhythm is
// ignored on purpose since the pedagogy reads pitch-shape before rhythm), and
// writes src/lib/learn/exercises.data.ts. Pure codegen: no app imports here.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const sourceDir = process.argv[2]
	? resolve(process.argv[2])
	: resolve(repoRoot, '..', 'learning-piano', 'practice');
const outFile = join(repoRoot, 'src', 'lib', 'learn', 'exercises.data.ts');

// Minor/major tonic for a given key signature (number of flats/sharps). Only the
// entries the notebook actually uses need to be exact; the rest are here so a new
// key does not silently break.
const MINOR_TONIC = { '-5': 'B♭', '-4': 'F', '-3': 'C', '-2': 'G', '-1': 'D', 0: 'A', 1: 'E' };
const MAJOR_TONIC = { '-4': 'A♭', '-3': 'E♭', '-2': 'B♭', '-1': 'F', 0: 'C', 1: 'G', 2: 'D' };

function keyName(fifths, mode) {
	const table = mode === 'minor' ? MINOR_TONIC : MAJOR_TONIC;
	const tonic = table[String(fifths)] ?? `${fifths} fifths`;
	return `${tonic} ${mode ?? 'major'}`;
}

function firstMatch(text, regex, fallback = null) {
	const match = text.match(regex);
	return match ? match[1] : fallback;
}

function parseExercise(id, xml) {
	// The app forbids em dashes in user-facing copy; source titles use them, so
	// fold " — " into a colon on the way in. En dashes in real ranges are fine.
	const rawTitle = firstMatch(xml, /<work-title>([\s\S]*?)<\/work-title>/) ?? id;
	const title = rawTitle.replace(/\s*—\s*/g, ': ');
	const clefSign = firstMatch(xml, /<clef[^>]*>[\s\S]*?<sign>([A-Z])<\/sign>/);
	const clef = clefSign === 'F' ? 'bass' : 'treble';
	const fifths = Number(firstMatch(xml, /<fifths>(-?\d+)<\/fifths>/, '0'));
	const mode = firstMatch(xml, /<mode>(\w+)<\/mode>/, 'major');

	const notes = [];
	const noteBlocks = xml.match(/<note\b[\s\S]*?<\/note>/g) ?? [];
	for (const block of noteBlocks) {
		if (/<rest\b/.test(block)) continue;
		const step = firstMatch(block, /<step>([A-G])<\/step>/);
		const octave = firstMatch(block, /<octave>(\d+)<\/octave>/);
		if (!step || octave === null) continue;
		const alter = Number(firstMatch(block, /<alter>(-?\d+)<\/alter>/, '0'));
		notes.push({ step, octave: Number(octave), alter });
	}

	return { id, title: title.trim(), clef, keyName: keyName(fifths, mode), notes };
}

function idFromFile(filename) {
	return filename.replace(/\.musicxml$/i, '').replace(/^practice-/, '');
}

const files = readdirSync(sourceDir)
	.filter((name) => name.toLowerCase().endsWith('.musicxml'))
	.sort();

if (files.length === 0) {
	console.error(`No .musicxml files found in ${sourceDir}`);
	process.exit(1);
}

const exercises = files.map((file) =>
	parseExercise(idFromFile(file), readFileSync(join(sourceDir, file), 'utf8'))
);

const body = exercises
	.map((exercise) => {
		const notes = exercise.notes
			.map((note) => `{ step: '${note.step}', octave: ${note.octave}, alter: ${note.alter} }`)
			.join(', ');
		return (
			`\t{\n` +
			`\t\tid: '${exercise.id}',\n` +
			`\t\ttitle: ${JSON.stringify(exercise.title)},\n` +
			`\t\tclef: '${exercise.clef}',\n` +
			`\t\tkeyName: ${JSON.stringify(exercise.keyName)},\n` +
			`\t\tnotes: [${notes}]\n` +
			`\t}`
		);
	})
	.join(',\n');

const out =
	`// GENERATED by tools/import-practice.mjs from the learning-piano notebook.\n` +
	`// Do not edit by hand; re-run \`node tools/import-practice.mjs\` to refresh.\n` +
	`import type { Exercise } from './exercises';\n\n` +
	`export const EXERCISES: Exercise[] = [\n${body}\n];\n`;

writeFileSync(outFile, out);
console.log(`Wrote ${exercises.length} exercises to ${outFile}`);
for (const exercise of exercises) {
	console.log(
		`  ${exercise.id.padEnd(26)} ${exercise.clef.padEnd(6)} ${exercise.keyName.padEnd(9)} ${exercise.notes.length} notes`
	);
}
